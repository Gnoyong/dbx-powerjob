import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const packagePath = resolve(root, "package.json");
const manifestPath = resolve(root, "manifest.json");
const backendVersionPath = resolve(root, "backend", "version.go");

function readVersion(packageSource) {
  const version = JSON.parse(packageSource).version;
  if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`package.json version must use the x.y.z format; received ${String(version)}.`);
  }
  return version;
}

function updateManifest(source, version) {
  const pattern = /(^\s*"version"\s*:\s*)"[^"]+"(\s*,?\s*$)/m;
  if (!pattern.test(source)) throw new Error("Top-level manifest version is missing.");
  return source.replace(pattern, `$1"${version}"$2`);
}

function generatedBackend(version) {
  return `// Code generated by scripts/sync-version.mjs; do not edit.\npackage main\n\nconst pluginVersion = "${version}"\n`;
}

async function main() {
  const [packageSource, manifestSource, backendSource] = await Promise.all([
    readFile(packagePath, "utf8"),
    readFile(manifestPath, "utf8"),
    readFile(backendVersionPath, "utf8"),
  ]);
  const version = readVersion(packageSource);
  const expectedManifest = updateManifest(manifestSource, version);
  const expectedBackend = generatedBackend(version);

  if (checkOnly) {
    if (manifestSource !== expectedManifest) throw new Error("manifest.json is out of sync with package.json. Run `node scripts/sync-version.mjs`.");
    if (backendSource !== expectedBackend) throw new Error("backend/version.go is out of sync with package.json. Run `node scripts/sync-version.mjs`.");
    console.log(`Version metadata is synchronized at ${version}.`);
    return;
  }

  await Promise.all([
    writeFile(manifestPath, expectedManifest),
    writeFile(backendVersionPath, expectedBackend),
  ]);
  console.log(`Synchronized manifest.json and backend/version.go to ${version}.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
